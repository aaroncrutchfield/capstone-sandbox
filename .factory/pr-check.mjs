// The PR title and body check (SHIP-007, 067), with no dependencies: `factory init` writes
// this file into a repo as .factory/pr-check.mjs, and the repo's CI runs it on every PR
// into the base branch (REPO-059). `factory doctor` fails when a repo's copy differs from
// the CLI's (REPO-061): change it here, never in a repo's copy.
//
// Run as a script, it reads the pull request from GITHUB_EVENT_PATH and the ticket pattern
// from .factory/repo.yaml, prints each problem with its fix and exits 1 when any is found.
import { readFileSync } from 'node:fs'
import process from 'node:process'
import { pathToFileURL } from 'node:url'

/** The conventional types a branch, commit or PR title may use. */
export const CHANGE_TYPES = ['feat', 'fix', 'docs', 'test', 'chore', 'refactor', 'perf', 'build', 'ci', 'style', 'revert']

/** The body's sections, in order; Slices only on a milestone landing PR. */
export const BODY_SECTIONS = ['Summary', 'Why', 'Requirement fulfillment', 'Flags', 'Slices']

/** Marks a requirement line may open with: met, met with a caveat, not met. */
export const REQUIREMENT_MARKS = ['✅', '⚠️', '⚠', '❌']

/** Words a PR body may show, its footer line and trailer block left out (SHIP-021). */
export const BODY_WORD_BUDGET = 350

/** Requirement lines past this many are written as one count line and a line per exception (SHIP-007). */
export const REQUIREMENT_LINES_MAX = 10

/** The trailer block's keys, in the order it holds them (SHIP-007). `Refs` stands in for `Closes` on a slice fix. */
export const TRAILER_ORDER = ['Closes', 'Milestone', 'Requested-by', 'Project-thread', 'Claude-Session', 'Co-Authored-By']

/** The footer line ship puts above the trailer block (SHIP-068). */
export const FOOTER_LINE = '🤖 Generated with [Claude Code](https://claude.com/claude-code)'

const TYPES = CHANGE_TYPES.join('|')
const HEADER = new RegExp(`^(${TYPES})\\(([a-z0-9][a-z0-9._/-]*)\\)!?: (\\S.*)$`)
const TRAILER_LINE = /^([A-Za-z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*):\s+(\S.*?)\s*$/
const HOST_FOOTER = /\n(?:[ \t]*\n)*---\n_Generated by \[Claude Code\]\(https:\/\/[^\s)]+\)_[ \t]*\n?$/

/** What is wrong with a conventional header (`<type>(<scope>): <text>`); undefined when nothing is. */
export function headerProblem(header) {
  if (header === '') return 'is empty'
  if (HEADER.test(header)) return undefined
  const typed = /^(\w+)(\(([^)]*)\))?(!)?:\s*(.*)$/.exec(header)
  const types = CHANGE_TYPES.join(', ')
  if (typed === null) return `doesn't start with a conventional type and scope (types: ${types})`
  const [, type, , scope, , rest] = typed
  if (!CHANGE_TYPES.includes(type ?? '')) return `'${type}' isn't a conventional type (use one of ${types})`
  if (scope === undefined || scope === '') return 'has no scope; name the area it changes in parentheses after the type'
  if (rest === undefined || rest === '') return 'says nothing after the colon'
  return 'must be `<type>(<scope>): <text>` with a lowercase scope and one space after the colon'
}

/** The PR title: a conventional type with a scope, e.g. `fix(seats): ...`. */
export function checkTitle(title) {
  const problem = headerProblem(title.trim())
  return problem === undefined ? [] : [{
    check: 'title',
    problem: `PR title '${title}': ${problem}`,
    fix: 'retitle it as `<type>(<scope>): <outcome>`, e.g. `feat(ship): run the gate before a PR opens`',
  }]
}

/**
 * The body without the one footer a Claude cloud session appends to every PR body it writes
 * (a `---` line, then `_Generated by [Claude Code](<https URL>)_`), so a fetched body checks
 * like the one shipped. Only that exact footer at the very end is removed.
 */
export function stripHostFooter(body) {
  return body.replace(/\r\n/g, '\n').replace(HOST_FOOTER, '\n')
}

/** The body with every footer the code host appended stripped (each edit can add one). */
export function stripHostFooters(body) {
  let prev
  let cur = body.replace(/\r\n/g, '\n')
  do {
    prev = cur
    cur = stripHostFooter(cur)
  } while (cur !== prev)
  return cur
}

/**
 * The PR body (SHIP-007, 067): Summary, Why, Requirement fulfillment and Flags in that
 * order (Slices after Flags only when landsMilestone), one one-sentence requirement line
 * per behavior or requirement (a count line and the exceptions past ten), at most
 * BODY_WORD_BUDGET words, no bare `#N`, no placeholder, no HTML comment, `<details>` block,
 * Tier line or Test plan, and a trailer block last: `Closes:` naming one ticket matching
 * ticketPattern, `Milestone:` only when landsMilestone, then `Requested-by:`,
 * `Project-thread:`, `Claude-Session:` and `Co-Authored-By:`, with nothing after it.
 */
export function checkPrBody(body, ctx) {
  const out = []
  const add = (problem, fix) => { out.push({ check: 'body', problem, fix }) }
  // SHIP-067: the footer a Claude cloud session appends after the trailers (once per write) is allowed; land drops it (SHIP-008).
  const lines = stripHostFooters(body).split('\n')
  const fenced = fencedLines(lines)
  const prose = (l) => l.replace(/`[^`]*`/g, '')

  // SHIP-067: what a commit can't carry.
  lines.forEach((l, i) => {
    if (fenced.has(i)) return
    if (prose(l).includes('<!--')) add(`line ${i + 1} opens an HTML comment, which the commit would carry as text`, 'remove the comment (a hint from the template, or a tool\'s marker); say it in plain words if the owner needs it')
    if (/<details\b/i.test(prose(l))) add(`line ${i + 1} opens a <details> block, which the commit would carry unfolded`, 'remove the block: keep only the flags worth keeping in the commit, and put evidence in a PR comment')
    if (/^\s*\*\*Tier:\*\*/.test(l)) add(`line ${i + 1} is a Tier line, which belongs in the review comment, not the commit`, 'remove the `**Tier:**` line; the run posts the tier in its review comment')
    if (/^##\s+Test plan\s*$/i.test(l)) add(`line ${i + 1} opens a Test plan section, which the commit doesn't keep`, 'remove the Test plan section; CI and the review comment hold the proof')
  })

  // Sections, in order.
  const headings = []
  lines.forEach((l, i) => {
    const m = /^##\s+(.+?)\s*$/.exec(l)
    if (m !== null && !fenced.has(i)) headings.push({ name: m[1] ?? '', line: i })
  })
  const want = BODY_SECTIONS.filter((s) => s !== 'Slices' || ctx.landsMilestone)
  const found = headings.map((h) => h.name.toLowerCase())
  for (const s of want) {
    if (!found.includes(s.toLowerCase())) add(`the body has no '## ${s}' section`, `add '## ${s}' in the template's order: ${want.join(', ')}`)
  }
  for (const h of headings) {
    if (!want.some((s) => s.toLowerCase() === h.name.toLowerCase())) continue
    const next = headings.find((x) => x.line > h.line)?.line ?? lines.length
    const own = lines.slice(h.line + 1, next)
    const stop = own.findIndex((l) => /^(🤖|Closes:|Refs:|Milestone:)/i.test(l.trim()))
    if ((stop < 0 ? own : own.slice(0, stop)).every((l) => l.trim() === '')) {
      add(`the '## ${cap(h.name.toLowerCase())}' section is empty`, `write it: the PR template says what goes under '## ${cap(h.name.toLowerCase())}'`)
    }
  }
  const known = found.filter((n) => want.some((s) => s.toLowerCase() === n))
  const order = want.map((s) => s.toLowerCase()).filter((s) => known.includes(s))
  if (known.join('\n') !== order.join('\n')) {
    add(`the sections are out of order (${known.map(cap).join(', ')})`, `put them in the template's order: ${want.join(', ')}`)
  }
  if (!ctx.landsMilestone && found.includes('slices')) {
    add('the body has a Slices section, but this PR doesn\'t land a milestone branch', 'remove the Slices section; only the PR landing a milestone/* branch lists its slices')
  }

  // Requirement lines: top-level bullets, one sentence each, a count line and the exceptions past ten.
  const req = headings.find((h) => h.name.toLowerCase() === 'requirement fulfillment')
  if (req !== undefined) {
    const end = headings.find((h) => h.line > req.line)?.line ?? lines.length
    const items = lines.slice(req.line + 1, end).filter((l, k) => /^[-*]\s+/.test(l) && !fenced.has(req.line + 1 + k))
    if (items.length === 0) {
      add('the Requirement fulfillment section has no requirement lines', 'add one line per behavior or requirement, e.g. `- ✅ SHIP-001: the gate records a receipt`')
    }
    if (items.length > REQUIREMENT_LINES_MAX) {
      add(`the Requirement fulfillment section has ${items.length} lines, over ${REQUIREMENT_LINES_MAX}`, 'write one count line (e.g. `- ✅ 14 behaviors, each proved by a test named for it`) and one line per exception')
    }
    for (const item of items) {
      const text = item.replace(/^[-*]\s+/, '')
      if (!REQUIREMENT_MARKS.some((m) => text.startsWith(m))) {
        add(`requirement line '${item.trim()}' doesn't say whether it's met`, 'start it with ✅ (met), ⚠️ (met with a caveat) or ❌ (not met), e.g. `- ✅ <ID>: <name>`')
      }
      if (sentences(text) > 1) {
        add(`requirement line '${item.trim()}' is longer than one sentence`, 'cut it to one sentence, the requirement and how we know it holds; put evidence in a PR comment')
      }
    }
  }

  // Slices lines on a milestone landing PR: mark, ticket, plain words, and a PR link once merged.
  const slices = headings.find((h) => h.name.toLowerCase() === 'slices')
  if (ctx.landsMilestone && slices !== undefined) {
    const end = headings.find((h) => h.line > slices.line)?.line ?? lines.length
    const items = lines.slice(slices.line + 1, end).filter((l) => /^[-*]\s+/.test(l))
    if (items.length === 0) add('the Slices section has no slice lines', 'add one line per slice, e.g. `- ✅ <TICKET> <slice in plain words> ([#N](<PR URL>))`, or `- ⏳ <TICKET> <slice>` while it is not merged')
    const sliceLine = new RegExp(`^(✅|⏳)\\s+(?:${ctx.ticketPattern})\\b\\s*:?\\s+\\S`)
    for (const item of items) {
      const text = item.replace(/^[-*]\s+/, '').trim()
      if (/^Fixes from/i.test(text)) continue
      if (!sliceLine.test(text)) {
        add(`slice line '${item.trim()}' needs a status mark, a ticket matching ${ctx.ticketPattern} and the slice in plain words`, 'write it as `- ✅ <TICKET> <slice in plain words> ([#N](<PR URL>))` when merged, or `- ⏳ <TICKET> <slice in plain words>` when not yet')
      } else if (text.startsWith('✅') && !/\[#\d+\]\(https?:\/\/[^)]+\)/.test(text)) {
        add(`merged slice line '${item.trim()}' has no PR link`, 'add its PR as a link, `([#N](<repo URL>/pull/N))`, at the end of the line')
      }
    }
  }

  // Template placeholders left in, outside code.
  lines.forEach((l, i) => {
    if (fenced.has(i)) return
    for (const m of prose(l).replace(/<!--[\s\S]*?-->/g, '').matchAll(/<([^<>\n/:=@"'!]+)>/g)) {
      const token = (m[1] ?? '').trim()
      if (token === '' || HTML_TAGS.has(token.toLowerCase().split(/\s/)[0] ?? '')) continue
      add(`line ${i + 1} still has the template placeholder '<${token}>'`, `replace '<${token}>' with the real text${/link|url/i.test(token) ? ' (the full URL)' : ''}`)
    }
  })

  // Bare #N.
  lines.forEach((l, i) => {
    if (fenced.has(i)) return
    const text = prose(l).replace(/\[[^\]]*\]\([^)]*\)/g, '').replace(/<[^>\s]*>/g, '').replace(/https?:\/\/\S+/g, '')
    for (const m of text.matchAll(/(^|[^\w&/])#(\d+)\b/g)) {
      add(`line ${i + 1} has a bare '#${m[2]}', which GitHub expands into that PR's full title`, `write it as a link, \`[#${m[2]}](<repo URL>/pull/${m[2]})\`, or say what happened in plain words`)
    }
  })

  // The trailer block, last.
  const block = trailerBlock(lines, fenced)
  const ticket = new RegExp(`^(?:${ctx.ticketPattern})$`)
  const closes = lines.map((l, i) => ({ l: l.trim(), i })).filter((x) => /^Closes:/i.test(x.l) && !fenced.has(x.i))
  if (closes.length === 0) {
    add('the body has no `Closes:` line', `end the body with its trailer block, starting \`Closes: <ticket>\`, one ticket matching ${ctx.ticketPattern}`)
  } else if (closes.length > 1) {
    add(`the body has ${closes.length} \`Closes:\` lines`, 'keep one `Closes:` line, the first line of the trailer block, naming the one ticket this PR closes')
  } else {
    const named = closes[0].l.replace(/^Closes:\s*/i, '').trim()
    if (!ticket.test(named)) add(`\`Closes:\` names '${named}', not one ticket matching ${ctx.ticketPattern}`, 'name exactly one ticket, e.g. `Closes: ASF-16`; other tickets are reached through their PR links')
  }
  if (block !== undefined) {
    const after = lines.slice(block.end).map((l, k) => ({ l: l.trim(), i: block.end + k })).filter((x) => x.l !== '')
    for (const x of after) {
      add(`line ${x.i + 1} ('${short(x.l)}') comes after the trailer block, so git wouldn't read the trailers`, 'remove it, or move it above the trailer block: the trailers are the body\'s last lines')
    }
    if (block.start > 0 && (lines[block.start - 1] ?? '').trim() !== '') {
      add('the trailer block isn\'t a paragraph of its own', 'put a blank line before `Closes:`, the trailer block\'s first line')
    }
    let at = 0
    const seen = new Set()
    for (let i = block.start; i < block.end; i++) {
      const key = TRAILER_LINE.exec((lines[i] ?? '').trim())?.[1] ?? ''
      const k = TRAILER_ORDER.findIndex((t) => t.toLowerCase() === key.toLowerCase())
      if (k < 0) {
        add(`trailer '${key}' (line ${i + 1}) isn't one the commit takes`, `remove it; the trailer block holds only ${TRAILER_ORDER.join(', ')}, in that order`)
        continue
      }
      if (k < at) add(`trailer '${key}' (line ${i + 1}) is out of order`, `order the trailer block ${TRAILER_ORDER.join(', ')}`)
      if (seen.has(k) && TRAILER_ORDER[k] !== 'Co-Authored-By') add(`the trailer block has more than one '${TRAILER_ORDER[k]}' line`, `keep one '${TRAILER_ORDER[k]}' line`)
      seen.add(k)
      at = Math.max(at, k)
    }
  } else if (closes.length === 1) {
    add('the `Closes:` line isn\'t in a trailer block at the end of the body', 'end the body with the trailer block, `Closes: <ticket>` first, with nothing after it')
  }
  // Trailer-shaped lines outside the block (a stray Co-Authored-By in Flags) aren't the commit's trailers.
  lines.forEach((l, i) => {
    if (fenced.has(i) || (block !== undefined && i >= block.start && i < block.end)) return
    const key = TRAILER_LINE.exec(l.trim())?.[1]
    if (key !== undefined && TRAILER_ORDER.slice(1).some((t) => t.toLowerCase() === key.toLowerCase())) {
      add(`line ${i + 1} is a '${key}' trailer outside the trailer block`, 'move it into the trailer block at the end, or remove it')
    }
  })
  const milestones = lines.filter((l, i) => /^Milestone:/i.test(l.trim()) && !fenced.has(i))
  if (milestones.length > 0 && !ctx.landsMilestone) {
    add('the body has a `Milestone:` line, but this PR doesn\'t land a milestone branch', 'remove the `Milestone:` line; only the PR landing a milestone/* branch carries it')
  }

  // The word budget: the footer line and the trailer block don't count (SHIP-021).
  const words = lines.reduce((n, l, i) => {
    if ((block !== undefined && i >= block.start) || l.trim().startsWith('🤖')) return n
    return n + l.split(/\s+/).filter((w) => /[\p{L}\p{N}]/u.test(w)).length
  }, 0)
  if (words > BODY_WORD_BUDGET) {
    add(`the body has ${words} words, over the ${BODY_WORD_BUDGET}-word budget`, 'keep Summary and Why to 1-2 sentences, one line per requirement and only the flags worth keeping in the commit; put evidence in a PR comment')
  }
  return out
}

/**
 * The trailer block: from the last `Closes:` line outside a fence, the trailer-shaped lines
 * that follow it with no blank line between. Undefined when there is no `Closes:` line.
 */
export function trailerBlock(lines, fenced = fencedLines(lines)) {
  let start = -1
  lines.forEach((l, i) => { if (!fenced.has(i) && /^Closes:/i.test(l.trim())) start = i })
  if (start < 0) return undefined
  let end = start + 1
  while (end < lines.length && TRAILER_LINE.test((lines[end] ?? '').trim())) end++
  return { start, end }
}

/** Tags a body may use on purpose; any other `<word>` is a placeholder. */
const HTML_TAGS = new Set(['br', 'b', 'i', 'em', 'strong', 'p', 'details', 'summary', 'sub', 'sup', 'kbd', 'code', 'pre', 'hr', 'img', 'a', 'ul', 'ol', 'li', 'table', 'tr', 'td', 'th', 'div', 'span', 'del', 'ins', 'mark', 'small'])

function cap(s) {
  return BODY_SECTIONS.find((b) => b.toLowerCase() === s) ?? s
}

function short(l) {
  return l.length > 60 ? `${l.slice(0, 57)}...` : l
}

/** How many sentences a line holds, ignoring code, link targets, URLs and abbreviations such as "e.g.". */
function sentences(text) {
  const prose = text
    .replace(/`[^`]*`/g, 'code')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/https?:\/\/\S+/g, 'url')
    .replace(/\b(e\.g|i\.e|etc|vs|cf)\./gi, '$1')
    .trim()
  return 1 + (prose.match(/[.!?]+\s+(?=\S)/g) ?? []).length
}

/** Indexes of lines inside ``` fences (examples, not the body's own text). */
function fencedLines(lines) {
  const inside = new Set()
  let open = false
  lines.forEach((l, i) => {
    if (/^\s*(```|~~~)/.test(l)) { open = !open; inside.add(i); return }
    if (open) inside.add(i)
  })
  return inside
}

/** The ticket pattern .factory/repo.yaml names, read without a YAML parser: plain, single- or double-quoted. */
export function ticketPatternOf(yaml) {
  const m = /^ticketPattern:\s*(.+?)\s*$/m.exec(yaml)
  if (m === null) return undefined
  const v = (m[1] ?? '').replace(/\s+#.*$/, '')
  if (v.startsWith("'")) return v.slice(1, v.lastIndexOf("'")).replace(/''/g, "'")
  if (v.startsWith('"')) return JSON.parse(v.slice(0, v.lastIndexOf('"') + 1))
  return v
}

/** CI: checks the pull request GitHub hands the workflow, exiting 1 with each problem named. */
function main() {
  const say = (s) => { process.stdout.write(`${s}\n`) }
  const event = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH ?? '', 'utf8'))
  const pr = event.pull_request
  if (pr === undefined) { say('not a pull request event: nothing to check'); return }
  const pattern = ticketPatternOf(readFileSync('.factory/repo.yaml', 'utf8'))
  if (pattern === undefined) { say('.factory/repo.yaml names no ticketPattern: run `factory init`'); process.exitCode = 1; return }
  const findings = [
    ...checkTitle(pr.title ?? ''),
    ...checkPrBody(pr.body ?? '', { ticketPattern: pattern, landsMilestone: /^milestone\/./.test(pr.head?.ref ?? '') }),
  ]
  if (findings.length === 0) { say('the PR title and body are ready to be the commit'); return }
  for (const f of findings) say(`✗ ${f.problem}\n  fix: ${f.fix}`)
  say(`\n${findings.length} problem(s): edit the PR's title or body on GitHub; this check runs again on each edit.`)
  process.exitCode = 1
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) main()
